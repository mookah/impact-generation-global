import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';

test('database publication, consent, idempotency, leases and private access', async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role; create schema storage;
      create table storage.buckets(id text primary key,name text,public boolean,file_size_limit integer,allowed_mime_types text[]);`);
    const sql = readFileSync(new URL('../supabase/migrations/20261023_content.sql', import.meta.url), 'utf8').replace('create extension if not exists pgcrypto;', '');
    await db.exec(sql);
    const query = (text, params=[]) => db.query(text,params);
    const value = async (text, params=[]) => (await query(text,params)).rows[0];
    assert.equal((await value("select igg_subscribe('pending@example.org','immediate','pendinghash') ok")).ok,true);
    assert.equal((await value("select igg_subscribe('pending@example.org','daily','replacement') ok")).ok,false);
    assert.equal((await value("select igg_confirm('wrong') ok")).ok,false);
    assert.equal((await value("select igg_confirm('pendinghash') ok")).ok,true);
    assert.equal((await value("select igg_confirm('pendinghash') ok")).ok,false,'confirmation token must be single use');
    await query("insert into igg_subscribers(email,status,frequency,confirmed_at) values ('daily@example.org','confirmed','daily',now()),('unconfirmed@example.org','pending','immediate',null),('removed@example.org','unsubscribed','immediate',now())");
    const article=await value("insert into igg_articles(slug,title,body,summary,status) values('story','Verified title','Verified report','Verified summary','approved') returning id");
    await query('select igg_publish($1,false,true)',[article.id]);
    assert.equal((await value('select count(*)::int n from igg_deliveries')).n,2,'only confirmed eligible subscribers');
    await assert.rejects(()=>query('select igg_publish($1,false,true)',[article.id]));
    assert.equal((await value('select count(*)::int n from igg_deliveries')).n,2,'repeat publication cannot enqueue');
    await query("update igg_articles set body='Edited report' where id=$1",[article.id]);
    assert.equal((await value('select count(*)::int n from igg_deliveries')).n,2,'edits do not notify');
    const first=(await query('select * from igg_claim_mail(false)')).rows;
    assert.equal(first.length,1,'daily notifications wait for digest');
    assert.equal((await query('select * from igg_claim_mail(false)')).rows.length,0,'worker leases prevent repeated claims');
    await query("update igg_deliveries set first_attempt_at=now()-interval '25 hours',lease_at=now()-interval '10 minutes' where id=$1",[first[0].id]);
    await query('select * from igg_claim_mail(false)');
    assert.equal((await value('select state from igg_deliveries where id=$1',[first[0].id])).state,'uncertain','never retry beyond provider idempotency window');
    const second=await value("insert into igg_articles(slug,title,body,summary,status) values('another','Second verified title','Report','Summary','approved') returning id");
    await query('select igg_publish($1,false,true)',[second.id]);
    await query("update igg_deliveries set due_at=now()-interval '1 hour' where frequency='daily'");
    await query('select igg_prepare_digests()'); await query('select igg_prepare_digests()');
    const digest=await value("select stories from igg_deliveries where frequency='digest'");
    assert.equal(digest.stories.length,2,'daily stories are combined into one email');
    assert.equal((await value("select count(*)::int n from igg_deliveries where frequency='digest'")).n,1);
    const september=await value("select id from igg_issues where slug='september-2026'");
    await query("update igg_issues set status='approved' where id=$1",[september.id]);
    await assert.rejects(()=>query('select igg_publish($1,true,true)',[september.id]),'empty issue cannot publish');
    await query("insert into igg_sources(id,text,published_at,updated_at,url,category,hash) values('370924362777718_1','Original',now(),now(),'https://www.facebook.com/1','News','h1')");
    const content={headline:'Headline',article:'Article',summary:'Summary',caption:'Caption',description:'SEO'};
    const rewrite=(await query('select * from igg_save_rewrite($1,$2,$3)', ['370924362777718_1','h1',content])).rows[0];
    await query("update igg_articles set status='approved' where id=$1",[rewrite.id]);
    await query("update igg_sources set hash='h2',text='Edited original' where id='370924362777718_1'");
    await query('select igg_invalidate_sources()');
    assert.equal((await value('select status from igg_articles where id=$1',[rewrite.id])).status,'draft');
    await query("update igg_articles set status='approved' where id=$1",[rewrite.id]);
    await assert.rejects(()=>query('select igg_publish($1,false,false)',[rewrite.id]),'stale source prevents publication');
    await query("update igg_articles set source_hash='h2' where id=$1",[rewrite.id]);
    await query('select igg_publish($1,false,false)',[rewrite.id]);
    await assert.rejects(()=>query('select * from igg_save_rewrite($1,$2,$3)', ['370924362777718_1','h2',content]),'AI cannot overwrite published stories');
    await assert.rejects(()=>query("insert into igg_media(storage_path,caption,category,approved,consent,hash) values('x','x','x',true,false,'x')"),'image approval requires consent');
    assert.equal((await value("select has_function_privilege('anon','igg_publish(uuid,boolean,boolean)','execute') ok")).ok,false);
    await query('set role anon');
    await assert.rejects(()=>query('select email from igg_subscribers'),'public clients cannot access subscriber data');
    await query('reset role');
    assert.equal((await value("select igg_rate('limit-test',1,3600) ok")).ok,true);
    assert.equal((await value("select igg_rate('limit-test',1,3600) ok")).ok,false);
  } finally { await db.close(); }
});
